"""Catalog of Docker Compose services a course can use, and the compose file built from it."""

from __future__ import annotations

from dataclasses import dataclass, field

import yaml

from codelabgen.models import EnvVar


@dataclass(frozen=True)
class Service:
    name: str
    definition: dict
    env: list[EnvVar] = field(default_factory=list)


CATALOG: dict[str, Service] = {
    "postgres": Service(
        "postgres",
        {
            "image": "postgres:17",
            "environment": {
                "POSTGRES_USER": "codelab",
                "POSTGRES_PASSWORD": "codelab",
                "POSTGRES_DB": "codelab",
            },
            "ports": ["5432:5432"],
            "volumes": ["postgres-data:/var/lib/postgresql/data"],
            "healthcheck": {
                "test": ["CMD-SHELL", "pg_isready -U codelab -d codelab"],
                "interval": "2s",
                "timeout": "3s",
                "retries": 30,
            },
        },
        [
            EnvVar(
                name="POSTGRES_URL",
                description="Connection string of the course Postgres (docker compose service)",
                default="postgresql://codelab:codelab@localhost:5432/codelab",
            )
        ],
    ),
    "redis": Service(
        "redis",
        {
            "image": "redis:8",
            "ports": ["6379:6379"],
            "healthcheck": {
                "test": ["CMD", "redis-cli", "ping"],
                "interval": "2s",
                "timeout": "3s",
                "retries": 30,
            },
        },
        [
            EnvVar(
                name="REDIS_URL",
                description="URL of the course Redis (docker compose service)",
                default="redis://localhost:6379/0",
            )
        ],
    ),
}


class UnknownService(Exception):
    pass


def resolve(names: list[str]) -> list[Service]:
    unknown = [n for n in names if n not in CATALOG]
    if unknown:
        raise UnknownService(f"unknown services: {', '.join(unknown)}; known: {', '.join(CATALOG)}")
    return [CATALOG[n] for n in dict.fromkeys(names)]


def compose_yaml(services: list[Service], project: str) -> str:
    doc: dict = {
        "name": project,
        "services": {s.name: s.definition for s in services},
    }
    volumes = {
        volume.split(":")[0]: {}
        for s in services
        for volume in s.definition.get("volumes", [])
        if not volume.startswith((".", "/"))
    }
    if volumes:
        doc["volumes"] = volumes
    header = "# Generated by codelabgen from the curriculum. Start with: docker compose up -d\n"
    return header + yaml.safe_dump(doc, sort_keys=False)
