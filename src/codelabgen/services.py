class UnknownService(Exception):
    pass


def custom_path(course_meta: Path) -> Path:
    return course_meta / "services.yaml"


def load_custom(course_meta: Path) -> dict[str, Service]:
    """Course-specific services from `.codelabgen/services.yaml`.

    Format: `<name>: {definition: <compose service>, env: [<EnvVar>, …]}`. The runtime
    planner writes it for services the built-in catalog doesn't have (a vector store,
    a message broker, …). A custom entry overrides a built-in one of the same name.
    """
    path = custom_path(course_meta)
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text()) or {}
    result = {}
    for name, entry in data.items():
        if not isinstance(entry, dict) or "image" not in (entry.get("definition") or {}):
            raise UnknownService(f"{path}: service {name!r} needs a definition with an image")
        env = [EnvVar.model_validate(v) for v in entry.get("env", [])]
        result[name] = Service(name, entry["definition"], env)
    return result


def available(course_meta: Path | None = None) -> dict[str, Service]:
    return {**CATALOG, **(load_custom(course_meta) if course_meta else {})}


def resolve(names: list[str], course_meta: Path | None = None) -> list[Service]:
    known = available(course_meta)
    unknown = [n for n in names if n not in known]
    if unknown:
        raise UnknownService(
            f"unknown services: {', '.join(unknown)}; known: {', '.join(known)}. "
            "Define others in .codelabgen/services.yaml"
        )
    return [known[n] for n in dict.fromkeys(names)]


def compose_yaml(services: list[Service], project: str) -> str:
    doc: dict = {
        "name": project,
        "services": {s.name: s.definition for s in services},
    }
    volumes = {
        volume.split(":")[0]: {}
        for s in services
        for volume in s.definition.get("volumes", [])
        if not volume.startswith((".", "/"))
    }
    if volumes:
        doc["volumes"] = volumes
    header = "# Generated by codelabgen from the curriculum. Start with: docker compose up -d\n"
    return header + yaml.safe_dump(doc, sort_keys=False)


def with_offset(service: Service, offset: int) -> Service:
    """The service with every published host port moved by `offset`, URLs to match."""
    if not offset:
        return service
    definition = dict(service.definition)
    moved: dict[str, str] = {}
    ports = []
    for mapping in definition.get("ports", []):
        parts = str(mapping).split(":")
        host, container = (parts[-2], parts[-1]) if len(parts) >= 2 else (parts[0], parts[0])
        new_host = str(int(host) + offset)
        moved[host] = new_host
        ports.append(":".join([*parts[:-2], new_host, container]))
    definition["ports"] = ports
    env = []
    for var in service.env:
        default = var.default
        for old, new in moved.items():
            if default:
                default = re.sub(rf"(localhost|127\.0\.0\.1):{old}\b", rf"\g<1>:{new}", default)
        env.append(var.model_copy(update={"default": default}))
    return Service(service.name, definition, env)


def published_ports(service: Service) -> list[tuple[int, int]]:
    """(host port, container port) pairs of a service definition."""
    result = []
    for mapping in service.definition.get("ports", []):
        parts = str(mapping).split(":")
        if len(parts) >= 2:
            result.append((int(parts[-2]), int(parts[-1].split("/")[0])))
    return result


def choose_offset(course_root: Path) -> int:
    """A stable per-course offset, a multiple of 10 between 10 and 9000."""
    return 10 * (zlib.crc32(str(course_root.resolve()).encode()) % 900 + 1)
