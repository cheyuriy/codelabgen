"""Catalog of Docker Compose services a course can use, and the compose file built from it."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import yaml

from codelabgen.models import EnvVar


@dataclass(frozen=True)
class Service:
    name: str
    definition: dict
    env: list[EnvVar] = field(default_factory=list)


