"""The course glossary: `.codelabgen/glossary.yaml` -> GLOSSARY.md + site tooltips."""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from codelabgen import curriculum as cur
from codelabgen.course import Course, atomic_write
from codelabgen.i18n import labels
from codelabgen.markdown import github_slug, relative_link
from codelabgen.models import GlossaryEntry

GLOSSARY_PAGE = "GLOSSARY.md"
ABBR_FILE = Path("assets") / "glossary-abbr.md"


def path(course: Course) -> Path:
    return course.meta / "glossary.yaml"


def load(course: Course) -> list[GlossaryEntry]:
    if not path(course).is_file():
        return []
    data = yaml.safe_load(path(course).read_text()) or []
    return [GlossaryEntry.model_validate(item) for item in data]


def save(course: Course, entries: list[GlossaryEntry]) -> None:
    entries = sorted(entries, key=lambda e: e.term.casefold())
    data = [
        e.model_dump(exclude_none=True, exclude_defaults=True) | {"term": e.term} for e in entries
    ]
    atomic_write(path(course), yaml.safe_dump(data, allow_unicode=True, sort_keys=False))


def add(
    course: Course,
    term: str,
    definition: str,
    aliases: list[str] | None = None,
    lesson: str | None = None,
) -> tuple[GlossaryEntry, bool]:
    """Add a term, or update its definition and aliases. Returns (entry, created)."""
    entries = load(course)
    for entry in entries:
        if entry.term.casefold() == term.casefold():
            entry.definition = definition
            entry.aliases = sorted(set(entry.aliases) | set(aliases or []))
            if lesson and not entry.first_lesson:
                entry.first_lesson = lesson
            save(course, entries)
            return entry, False
    entry = GlossaryEntry(
        term=term, definition=definition, aliases=aliases or [], first_lesson=lesson
    )
    save(course, [*entries, entry])
    return entry, True


def anchor(term: str) -> str:
    return github_slug(term)


def heading(term: str) -> str:
    """The term as heading text: in code ticks when `_` or `*` would turn it into emphasis."""
    if re.search(r"(^|\W)[_*]|[_*]($|\W)", term):
        return f"`{term}`"
    return term


def link(course: Course, term: str, from_file: Path) -> str:
    """Relative link from a Markdown file to the term's entry in GLOSSARY.md."""
    entries = {e.term.casefold(): e for e in load(course)}
    entry = entries.get(term.casefold())
    if entry is None:
        raise KeyError(f"no glossary term {term!r}; add it with `codelabgen glossary add`")
    return f"{relative_link(from_file.resolve(), course.root / GLOSSARY_PAGE)}#{anchor(entry.term)}"


def build(course: Course) -> list[Path]:
    """Write GLOSSARY.md and the abbreviation file the site appends to every page."""
    entries = sorted(load(course), key=lambda e: e.term.casefold())
    config = course.load_config()
    text = labels(config.language)
    lesson_dirs: dict[str, Path] = {}
    if (course.meta / "curriculum.yaml").is_file():
        lesson_dirs = {item.id: item.rel_dir for item in cur.lessons(cur.load(course))}

    lines = [f"# {text['glossary']}", "", text["glossary_intro"], ""]
    for entry in entries:
        lines += [f"## {heading(entry.term)}", "", entry.definition, ""]
        if entry.aliases:
            lines += [f"*{text['also']}: {', '.join(entry.aliases)}*", ""]
        if entry.first_lesson and entry.first_lesson in lesson_dirs:
            target = (lesson_dirs[entry.first_lesson] / "README.md").as_posix()
            lines += [f"{text['first_used']} [{entry.first_lesson}]({target})", ""]
    page = course.root / GLOSSARY_PAGE
    atomic_write(page, "\n".join(lines).rstrip() + "\n")

    abbreviations = []
    for entry in entries:
        definition = " ".join(entry.definition.split()).replace("]", ")")
        for name in [entry.term, *entry.aliases]:
            abbreviations.append(f"*[{name}]: {definition}")
    abbr = course.root / ABBR_FILE
    header = "<!-- Generated by codelabgen glossary build: tooltips for the site -->\n"
    atomic_write(abbr, header + "\n".join(abbreviations) + ("\n" if abbreviations else ""))
    return [page, abbr]
